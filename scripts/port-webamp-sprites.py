#!/usr/bin/env python3
"""Generate SkinSprites.swift from Webamp's js/skinSprites.ts (MIT, see NOTICE).

Also emits the TEXT sheet (text.bmp) that Webamp builds from FONT_LOOKUP at load time:
CHARACTER_<char code> at x = column * 5, y = row * 6, 5x6.

Usage: scripts/port-webamp-sprites.py <path to skinSprites.ts> > \
         Packages/SkinKit/Sources/SkinKit/Sprites/SkinSprites.swift
Raw file: https://raw.githubusercontent.com/captbaritone/webamp/master/packages/webamp/js/skinSprites.ts
"""
import re
import sys

src = open(sys.argv[1], encoding="utf-8").read()
src = re.sub(r"/\*.*?\*/", "", src, flags=re.S)  # drop commented-out sheets (GENEX)
body = src[src.index("const sprites: SpriteMap = {"):]

sheets = []
for m in re.finditer(r"^  ([A-Z_]+): \[(.*?)^  \],", body, flags=re.S | re.M):
    sprites = []
    for s in re.finditer(r"\{(.*?)\}", m.group(2), flags=re.S):
        fields = dict(re.findall(r"(\w+):\s*(\"[^\"]*\"|\d+)", s.group(1)))
        sprites.append((fields["name"].strip('"'), *(int(fields[k]) for k in ("x", "y", "width", "height"))))
    sheets.append((m.group(1), sprites))

# FONT_LOOKUP: key -> [row, column]. Keys are bare identifiers, quoted strings or [UTF8_ELLIPSIS].
font_block = src[src.index("export const FONT_LOOKUP"):]
font_block = font_block[font_block.index("= {") :font_block.index("\n};")]
text_sprites = []
for line in font_block.splitlines()[1:]:
    m = re.match(r"^\s*(.+?): \[(\d+), (\d+)\],?$", line)
    if not m:
        continue
    key = m.group(1)
    if key == "[UTF8_ELLIPSIS]":
        char = "\u2026"
    elif key[0] in "'\"":
        char = key[1:-1].replace("\\\\", "\\")
    else:
        char = key
    assert len(char) == 1, key
    text_sprites.append((f"CHARACTER_{ord(char)}", int(m.group(3)) * 5, int(m.group(2)) * 6, 5, 6))
assert len(text_sprites) == 69, len(text_sprites)

out = [
    "// Generated by scripts/port-webamp-sprites.py from Webamp's skinSprites.ts.",
    "// Webamp is MIT licensed; see NOTICE. Do not edit by hand.",
    "",
    "public enum SkinSprites {",
    "    /// Sprite definitions keyed by sheet name (the bitmap's base file name, uppercased).",
    "    public static let sheets: [String: [Sprite]] = [",
]
for sheet, sprites in sheets:
    out.append(f'        "{sheet}": [')
    for name, x, y, w, h in sprites:
        out.append(f'            Sprite(name: "{name}", x: {x}, y: {y}, width: {w}, height: {h}),')
    out.append("        ],")
out.append('        "TEXT": [')
for name, x, y, w, h in text_sprites:
    out.append(f'            Sprite(name: "{name}", x: {x}, y: {y}, width: {w}, height: {h}),')
out.append("        ],")
out += ["    ]", "}", ""]
sys.stdout.write("\n".join(out))
